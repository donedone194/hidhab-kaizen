// Helper to look up a wilaya by id or code
export function getWilayaById(id: number | string): Wilaya | undefined {
  const numericId = typeof id === "string" ? parseInt(id, 10) : id;
  return ALGERIA_WILAYAS.find((w) => w.id === numericId);
}

// Helper to get communes for a given wilaya
export function getCommunesByWilayaId(wilayaId: number | string): Commune[] {
  const wilaya = getWilayaById(wilayaId);
  return wilaya ? wilaya.communes : [];
}

